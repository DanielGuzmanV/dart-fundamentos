  // Sets (Set)
  // Colecciones de elementos únicos. No admiten duplicados.
void main() {
  // Con tipo de datos
  Set<int> numeros = {1, 2, 3, 3, 4};
  print(numeros);

  Set<String> nombres = {'marco', 'pablo', 'pedro', 'pablo'};
  print(nombres);

  // Sin tipo de datos
  Set numbers = {1,2,3,4,5,5,6,6};
  print(numbers);

}